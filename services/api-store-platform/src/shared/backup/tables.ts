import { createHash } from 'crypto'
import { getTableConfig, PgTable } from 'drizzle-orm/pg-core'

import * as store from '../../db/schema/store'

/** store table name → why it is NOT in a backup. Every other store table is backed up. */
export const EXCLUDED_TABLES: Record<string, string> = {
	offline_sync_states: 'sync bookkeeping must stay current, not roll back',
	sync_mutations: 'replay idempotency must stay current, not roll back',
	negative_quantity_snapshots: 'derived: regenerated by cron',
	product_import_sessions: 'transient import drafts',
	notification_reads: 'per-user UI state',
}

export type BackupTable = { name: string; columns: string[] }

/**
 * Backed-up store tables in restore order: declaration order of `schema/store.ts`,
 * where parents come before their child tables (invoice → items). Delete runs in reverse.
 * A new store table is backed up by default; exclude it above with a reason.
 */
export const BACKUP_TABLES: BackupTable[] = (Object.values(store) as unknown[])
	.filter((value): value is PgTable => value instanceof PgTable)
	.map(getTableConfig)
	.filter(table => !(table.name in EXCLUDED_TABLES))
	.map(table => ({
		name: table.name,
		columns: table.columns.map(column => `${column.name}:${column.columnType}`),
	}))

/**
 * Fingerprint of the backed-up tables and their columns. A restore refuses a file
 * with another fingerprint: its rows would not fit the tables 1 : 1.
 * shortcut: no conversion of older files; add one when a migration changes a backed-up table.
 */
export const BACKUP_SCHEMA_FINGERPRINT = createHash('sha256')
	.update(JSON.stringify(BACKUP_TABLES))
	.digest('hex')
	.slice(0, 16)
